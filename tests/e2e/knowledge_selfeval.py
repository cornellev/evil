"""Self-built cev-knowledge eval: no hand-written questions needed.

- title questions: "where is the doc about <page title>" should find that page
- passage questions: 4 fairly distinctive words from a random section should find that section's page
- attachment questions (phase 6): "where is the <file name>" should find that attachment
- reworded questions (optional file, [{"page_id", "question"}]): a question about a section in other words than the
  page uses. Generated by gemma4 on thor from sampled sections (not kept in git: they paraphrase team pages).
Prints hit@1 / hit@3 / MRR per kind, keyword-only and (when the index has vectors and KNOWLEDGE_EMBED_URL answers)
keyword + meaning.

11-11, real index (444 title, 250 passage, 90 reworded), hit@3:
  keyword only                          title 0.98  passage 0.99  reworded 0.30
  + embeddinggemma, rank fusion (RRF)   title 0.97  passage 0.70  reworded 0.47
  + embeddinggemma, coverage-weighted   title 0.99  passage 0.98  reworded 0.58   <- shipped
  embeddinggemma alone                  title 0.94  passage 0.51  reworded 0.64
  qwen3-embedding:0.6b was worse than embeddinggemma in every setup (and 4.6 GB on thor vs 0.7 GB).

On the NUC: docker compose exec -T knowledge python - /knowledge/knowledge.db [reworded.json] < tests/e2e/knowledge_selfeval.py
"""
import collections
import json
import math
import random
import re
import sqlite3
import sys

from evil.knowledge import embeddings as emb
from evil.knowledge import search

db = sqlite3.connect(f"file:{sys.argv[1]}?mode=ro", uri=True)
db.row_factory = sqlite3.Row
WORD = re.compile(r"[a-z][a-z0-9]{3,}")
pages = {r["id"]: r for r in db.execute("SELECT * FROM pages")}
chunks = db.execute("SELECT page_id, ordinal, heading, text FROM chunks").fetchall()
df = collections.Counter()
for c in chunks:
    df.update(set(WORD.findall(c["text"].lower())))
N = len(chunks)
rnd = random.Random(7)
cases = []
for pid, p in sorted(pages.items()):
    if p["kind"] == "page":
        words = [w for w in re.findall(r"[A-Za-z0-9]+", p["title"]) if len(w) > 1]
        if len(words) >= 1:
            cases.append(("title", f"where is the doc about {' '.join(words).lower()}", pid))
    elif p["kind"] in ("attachment", "attachment_link_only"):
        words = [w for w in re.findall(r"[A-Za-z][A-Za-z0-9]+", re.sub(r"\.[A-Za-z0-9]{2,5}$", "", p["title"]))
                 if len(w) > 1]
        if len(words) >= 2:
            cases.append(("attach", f"where is the {' '.join(words).lower()} file", pid))
for c in rnd.sample([c for c in chunks if pages[c["page_id"]]["kind"] == "page" and len(c["text"].split()) >= 80], 250):
    title = set(WORD.findall(pages[c["page_id"]]["title"].lower()))
    ws = sorted({w for w in WORD.findall(c["text"].lower()) if w not in title and df[w] >= 2},
                key=lambda w: math.log(N / df[w]), reverse=True)[4:16]
    if len(ws) >= 4:
        cases.append(("passage", " ".join(rnd.sample(ws, 4)), c["page_id"]))
if len(sys.argv) > 2:
    for x in json.load(open(sys.argv[2])):
        if x["page_id"] in pages:
            cases.append(("reworded", x["question"], x["page_id"]))


def run(label, vectors=None, qvecs=None):
    res = collections.defaultdict(lambda: [0, 0, 0, 0.0])
    for i, (kind, q, want) in enumerate(cases):
        hits = search.search(db, q, limit=10, sources=["confluence"], vectors=vectors,
                             query_vec=None if qvecs is None else qvecs[i])
        ids = [h["id"] for h in hits]
        r = ids.index(want) + 1 if want in ids else None
        m = res[kind]; m[0] += 1; m[1] += r == 1; m[2] += bool(r and r <= 3); m[3] += 1 / r if r else 0
    print(label)
    for kind, (n, h1, h3, mrr) in sorted(res.items()):
        print(f"  {kind:8} n={n:3}  hit@1 {h1/n:.2f}  hit@3 {h3/n:.2f}  MRR {mrr/n:.3f}")


run("keyword only")
client = emb.EmbedClient()
vectors = emb.load_vectors(db, client.model) if client.enabled else None
if vectors is not None and len(vectors.chunk_ids):
    try:
        qvecs = []
        for i in range(0, len(cases), 64):
            qvecs.extend(client.embed([emb.query_text(client.model, q) for _, q, _ in cases[i:i + 64]]))
        run(f"keyword + meaning ({client.model}, {len(vectors.chunk_ids)} sections embedded)", vectors, qvecs)
    except emb.EmbedUnavailable as exc:
        print("keyword + meaning: skipped,", exc)
else:
    print("keyword + meaning: skipped (no vectors in the index, or KNOWLEDGE_EMBED_URL not set)")
q = "motor controller design"
print("deterministic:", [h["id"] for h in search.search(db, q)] == [h["id"] for h in search.search(db, q)])
